// Writes the recorder mod's schema constants from the TypeScript registry (fields.ts, phases.ts):
// mod/common/src/generated/java/dev/mcpn/recorder/schema/{PlayerFields,ServerFields,Phases}.java.
// The mod writes fields through these constants, so a name the registry lacks does not compile,
// and it checks at startup that it wrote exactly the fields the registry has for its release.
//
//   node recorder/schema/gen-java.ts [--check]   (--check fails when the checked-in files differ)

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PLAYER_FIELDS, SERVER_FIELDS, type FieldSpec } from './fields.ts';
import { PACKET_HANDLING, BETWEEN_TICKS, PLAYER_PHASES } from './phases.ts';

const dir = fileURLToPath(new URL('../mod/common/src/generated/java/dev/mcpn/recorder/schema/', import.meta.url));

const constant = (key: string) => key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z])([A-Z][a-z])/g, '$1_$2').toUpperCase();
const javaString = (value: string) => JSON.stringify(value);

function fieldsClass(name: string, doc: string, fields: Record<string, FieldSpec>): string {
    const entries = Object.entries(fields);
    let out = `// Generated by recorder/schema/gen-java.ts from fields.ts. Do not edit.\npackage dev.mcpn.recorder.schema;\n\n`;
    out += `/** ${doc} */\npublic final class ${name} {\n    private ${name}() {\n    }\n\n`;
    for (const [key, spec] of entries) {
        out += `    /** ${spec.vanilla.replace(/\*\//g, '* /')} (${spec.type}${spec.versions ? `, ${spec.versions}` : ''}) */\n`;
        out += `    public static final String ${constant(key)} = ${javaString(key)};\n`;
    }
    out += `\n    /** Every field: key, type, version range ("" for every release). */\n    public static final String[][] ALL = {\n`;
    for (const [key, spec] of entries) out += `        {${javaString(key)}, ${javaString(spec.type)}, ${javaString(spec.versions ?? '')}},\n`;
    out += '    };\n}\n';
    return out;
}

function phasesClass(): string {
    let out = `// Generated by recorder/schema/gen-java.ts from phases.ts. Do not edit.\npackage dev.mcpn.recorder.schema;\n\n`;
    out += '/** The local player\'s phases, in the order 1.20.4 runs them, and the packet pseudo-phases. */\npublic final class Phases {\n    private Phases() {\n    }\n\n';
    for (const phase of PLAYER_PHASES) out += `    public static final String ${constant(phase)} = ${javaString(phase)};\n`;
    out += `    public static final String PACKET_HANDLING = ${javaString(PACKET_HANDLING)};\n`;
    out += `    public static final String BETWEEN_TICKS = ${javaString(BETWEEN_TICKS)};\n\n`;
    out += `    public static final String[] ORDER = {${PLAYER_PHASES.map(javaString).join(', ')}};\n}\n`;
    return out;
}

const files: Record<string, string> = {
    'PlayerFields.java': fieldsClass('PlayerFields', 'The local player\'s recorded fields (fields.ts PLAYER_FIELDS).', PLAYER_FIELDS),
    'ServerFields.java': fieldsClass('ServerFields', 'The server\'s view, recorded once per server tick (fields.ts SERVER_FIELDS).', SERVER_FIELDS),
    'Phases.java': phasesClass(),
};

const check = process.argv.includes('--check');
let stale = 0;
mkdirSync(dir, { recursive: true });
for (const [name, content] of Object.entries(files)) {
    const path = `${dir}${name}`;
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    if (current === content) continue;
    stale += 1;
    if (check) console.error(`${name} is out of date: run node recorder/schema/gen-java.ts`);
    else writeFileSync(path, content);
}
if (check && stale > 0) process.exit(1);
console.log(check ? 'generated Java is up to date' : `wrote ${stale} file(s) to ${dir}`);
