// Writes scenarios/generated/types.ts: the block names with their state properties, and the
// effect, attribute, entity, item and enchantment names, as the union over every release from
// 1.14 that minecraft-data knows. A scenario that names something a release lacks is skipped on
// that release by build.ts; a name no release has fails typechecking.
//
//   node recorder/scenarios/gen-types.ts

import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { snake, versionAtLeast } from './dsl/names.ts';

const require = createRequire(import.meta.url);
const mcData = require('minecraft-data') as {
    (version: string): McData;
    supportedVersions: { pc: string[] };
};

interface McState { name: string; type: 'enum' | 'bool' | 'int'; values?: string[]; num_values: number }
interface McData {
    blocksArray: { name: string; states?: McState[] }[];
    effectsArray: { name: string }[];
    attributesArray?: { resource: string }[];
    entitiesArray: { name: string }[];
    itemsArray: { name: string }[];
    enchantmentsArray: { name: string }[];
}

const versions = mcData.supportedVersions.pc.filter(v => /^\d+\.\d+(\.\d+)?$/.test(v) && versionAtLeast(v, '1.14'));

const blocks = new Map<string, Map<string, Set<string>>>();
const effects = new Set<string>();
const attributes = new Set<string>();
const entities = new Set<string>();
const items = new Set<string>();
const enchantments = new Set<string>();

for (const version of versions) {
    const data = mcData(version);
    for (const block of data.blocksArray) {
        const props = blocks.get(block.name) ?? new Map<string, Set<string>>();
        blocks.set(block.name, props);
        for (const state of block.states ?? []) {
            const values = props.get(state.name) ?? new Set<string>();
            props.set(state.name, values);
            if (state.type === 'bool') { values.add('true'); values.add('false'); }
            else if (state.type === 'enum') for (const value of state.values ?? []) values.add(value);
            else for (const value of state.values ?? []) values.add(value);
        }
    }
    for (const effect of data.effectsArray) effects.add(snake(effect.name));
    for (const attribute of data.attributesArray ?? []) attributes.add(attribute.resource.replace(/^(minecraft:)?(generic|player|zombie|horse)\./, ''));
    for (const entity of data.entitiesArray) entities.add(entity.name);
    for (const item of data.itemsArray) items.add(item.name);
    for (const enchantment of data.enchantmentsArray) enchantments.add(enchantment.name);
}

const quote = (value: string) => `'${value}'`;
const union = (values: Iterable<string>) => [...values].sort().map(quote).join('\n    | ');
const isIntLike = (values: Set<string>) => [...values].every(v => /^\d+$/.test(v));

let out = `// Generated by scenarios/gen-types.ts from minecraft-data (${versions[0]} - ${versions.at(-1)}). Do not edit.\n\n`;
out += `export type BlockName =\n    | ${union(blocks.keys())};\n\n`;
out += 'export interface BlockProps {\n';
for (const name of [...blocks.keys()].sort()) {
    const props = blocks.get(name)!;
    if (props.size === 0) { out += `    ${name}: {};\n`; continue; }
    const members = [...props.keys()].sort().map(prop => {
        const values = props.get(prop)!;
        const type = values.size === 0 ? 'number'
            : isIntLike(values)
            ? [...values].sort((a, b) => Number(a) - Number(b)).join(' | ')
            : [...values].sort().map(v => (v === 'true' || v === 'false' ? v : quote(v))).join(' | ');
        return `${/^\w+$/.test(prop) ? prop : quote(prop)}?: ${type}`;
    });
    out += `    ${name}: { ${members.join('; ')} };\n`;
}
out += '}\n\n';
out += `export type EffectName =\n    | ${union(effects)};\n\n`;
out += `export type AttributeName =\n    | ${union(attributes)};\n\n`;
out += `export type EntityName =\n    | ${union(entities)};\n\n`;
out += `export type ItemName =\n    | ${union(items)};\n\n`;
out += `export type EnchantmentName =\n    | ${union(enchantments)};\n`;

const dir = fileURLToPath(new URL('./generated/', import.meta.url));
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}types.ts`, out);
console.log(`types.ts: ${blocks.size} blocks, ${effects.size} effects, ${attributes.size} attributes, ${entities.size} entities, ${items.size} items over ${versions.length} releases`);
