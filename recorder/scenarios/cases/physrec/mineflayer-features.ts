const item = (id: string, count = 1, enchantments: Readonly<Record<string, number>> = {}): PhysrecItem => ({ id, count, enchantments })
// The player at x=0.5 of a lane, facing +x; the lane's station is at x=2 (pitch 30 looks at its middle).
// serverMoves: a feature case keeps the server's position packets (a respawn, a pearl) instead of failing on them.
const lane = (z: number, extra: Partial<KaseSpec> = {}): KaseSpec => ({ area: 'features', at: [0.5, 0, z + 0.5], yaw: 270, pitch: 0, features: true, serverMoves: true, tier: 3, ...extra })
const cmd = (...commands: string[]): PhysrecStep => server(...commands.map(command))
// Runs at the player, so relative coordinates are the player's: ~1.5 ~ ~ is the station in front of it.
const atPlayer = (text: string) => command(`execute as @p at @s run ${text}`)
// Commands whose syntax differs by version: each argument is a commandBy map { since: text } (null: none there).
// The text for the versions today's command already worked on stays as it was; older versions get their own syntax.
const cmdBy = (...variants: Readonly<Record<string, string | null>>[]): PhysrecStep => server(...variants.map(commandBy))
// The same, as the player: execute as/at (1.13+) or execute <entity> <x y z> (before).
const atPlayerText = (text: string): string => `execute as @p at @s run ${text}`
const legacyAt = (text: string): string => `execute @p ~ ~ ~ ${text}`
// xp before 1.13: xp <n>[L] <player> (no add/set)
const xpLevels = (n: number): Record<string, string> => ({ '1.13': `xp add @p ${n} levels`, '1.8': `xp ${n}L @p` })
const wait = (n = 3) => ticks(n)
const openStation = (name = 'container'): PhysrecStep[] => [look(270, 30), press(USE, 1), screen(name, 60), wait(5)]

