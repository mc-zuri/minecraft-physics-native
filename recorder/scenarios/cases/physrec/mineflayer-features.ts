// Ported from physics-data-generator catalog/src/cases/mineflayer-features.mjs; maintained here now.
// Feature cases: what a mineflayer bot does besides moving, played by the vanilla client so the recording holds the
// real packets in both directions: chat, HUD (title, boss bar, scoreboard, teams, tab list), health and death,
// experience, time and weather, digging and placing, windows (chest, furnace, crafting, anvil, enchanting, villager,
// horse), books, signs, command blocks, creative slots, entities (attack, leash, equipment), fishing, beds, resource
// packs and a kick. Each case also records the vanilla client's state whenever it changes (client_state), the state a
// bot replaying the same packets must reach. Needs an adapter with Bridge.supportsFeatures; skipped elsewhere.
//
// Window slots (26.x): chest 0-26 + main 27-53 + hotbar 54-62; furnace 0 in, 1 fuel, 2 out, main 3-29, hotbar 30-38;
// crafting table 0 out, 1-9 grid, main 10-36, hotbar 37-45; anvil 0, 1 in, 2 out, main 3-29, hotbar 30-38;
// enchanting 0 item, 1 lapis, main 2-28, hotbar 29-37; merchant 0, 1 pay, 2 out, main 3-29, hotbar 30-38;
// player inventory 0 out, 1-4 grid, 5-8 armor, main 9-35, hotbar 36-44, 45 offhand.
// setup.inventory uses inventory indexes: hotbar 0-8, main 9-35, armor 36-39, offhand 40.
