// Ported from physics-data-generator catalog/src/cases/java-ground.mjs; maintained here now.
// Ground movement on flat stone: every direction with walk / sprint / sneak / sprint+sneak, accelerate then coast to a
// stop; jumps in every direction; held-jump hopping and the jump delay; view edge cases (odd yaw, wrapped yaw,
// pitch extremes); sprint start and stop rules.
import './_areas/index.ts'
import { DIRECTIONS, JUMP, SNEAK, SPRINT, hold, kase, press, release, releaseAll, repeat, stable, stopped, ticks, turn, until } from '../../dsl/physrec.ts'

const flat = { area: 'flat', at: [0.5, 0, 0.5], expect: 'on:stone', tier: 0 }
const out = []
const MODES = { walk: [], sprint: [SPRINT], sneak: [SNEAK], sprint_sneak: [SPRINT, SNEAK] }

for (const [dir, keys] of Object.entries(DIRECTIONS)) {
  for (const [mode, extra] of Object.entries(MODES)) {
    out.push(kase(`j_${mode}_${dir}`, { ...flat, tags: [mode, 'ground'] },
      press([...keys, ...extra], 40),
      stopped(3),
      ticks(3),
    ))
  }
  out.push(kase(`j_jump_walk_${dir}`, { ...flat, tags: ['jump', 'ground'] },
    hold(...keys),
    press(JUMP, 1),
    until('onGround', 40),
    release(...keys),
    stopped(3),
    ticks(3),
  ))
  out.push(kase(`j_jump_sprint_${dir}`, { ...flat, tags: ['jump', 'sprint'] },
    hold(...keys, SPRINT),
    ticks(10),
    press(JUMP, 1),
    until('onGround', 40),
    releaseAll(),
    stopped(3),
    ticks(3),
  ))
  out.push(kase(`j_jump_sneak_${dir}`, { ...flat, tags: ['jump', 'sneak'] },
    hold(...keys, SNEAK),
    ticks(10),
    press(JUMP, 1),
    until('onGround', 40),
    releaseAll(),
    stopped(3),
    ticks(3),
  ))
}

out.push(
  kase('j_jump_standing', { ...flat, tags: ['jump'], checks: 'highest>1.2' },
    press(JUMP, 1),
    until('onGround', 40),
    ticks(5),
  ),
  // Holding jump: the 10-tick delay between hops (noJumpDelay), on the spot and while sprinting.
  kase('j_hop_held', { ...flat, tags: ['jump'] },
    press(JUMP, 60),
    stopped(3),
    ticks(3),
  ),
  kase('j_hop_held_sprint', { ...flat, tags: ['jump', 'sprint'] },
    press(['forward', SPRINT, JUMP], 60),
    releaseAll(),
    stopped(3),
  ),
  kase('j_hop_held_walk', { ...flat, tags: ['jump', 'walk'] },
    press(['forward', JUMP], 60),
    releaseAll(),
    stopped(3),
  ),
  // Jump pressed on the landing tick and one tick late.
  kase('j_jump_on_landing', { ...flat, tags: ['jump'] },
    press(JUMP, 1),
    until('onGround', 40),
    press(JUMP, 1),
    until('onGround', 40),
    ticks(5),
  ),
  kase('j_jump_released_in_air', { ...flat, tags: ['jump'] },
    press(JUMP, 3),
    ticks(3),
    press(JUMP, 20),
    ticks(5),
  ),

  // Sprint rules: starting a sprint needs forward; back/strafe with sprint key only walk; releasing sprint keeps walking.
  kase('j_sprint_then_release_sprint', { ...flat, tags: ['sprint'] },
    hold('forward', SPRINT),
    ticks(20),
    release(SPRINT),
    ticks(20),
    releaseAll(),
    stopped(3),
  ),
  kase('j_sprint_key_first', { ...flat, tags: ['sprint'] },
    hold(SPRINT),
    ticks(3),
    hold('forward'),
    ticks(25),
    releaseAll(),
    stopped(3),
  ),
  kase('j_double_tap_forward', { ...flat, tags: ['sprint'] },
    press('forward', 1),
    ticks(2),
    press('forward', 25),
    stopped(3),
  ),
  kase('j_sprint_to_sneak', { ...flat, tags: ['sprint', 'sneak'] },
    hold('forward', SPRINT),
    ticks(20),
    hold(SNEAK),
    ticks(15),
    releaseAll(),
    stopped(3),
  ),
  kase('j_sprint_reverse', { ...flat, tags: ['sprint'] },
    press(['forward', SPRINT], 20),
    press(['back'], 20),
    stopped(3),
  ),

  // View: odd yaw (float trig), yaw past 360 and negative, pitch extremes (walking ignores pitch), steady turning.
  kase('j_walk_yaw_37_5', { ...flat, yaw: 37.5, tags: ['walk', 'view'] },
    press('forward', 30),
    stopped(3),
  ),
  kase('j_sprint_yaw_123_456', { ...flat, yaw: 123.456, tags: ['sprint', 'view'] },
    press(['forward', SPRINT], 30),
    stopped(3),
  ),
  kase('j_walk_yaw_765', { ...flat, yaw: 765, tags: ['walk', 'view'] },
    press('forward', 30),
    stopped(3),
  ),
  kase('j_walk_yaw_neg_1000', { ...flat, yaw: -1000, tags: ['walk', 'view'] },
    press('forward', 30),
    stopped(3),
  ),
  kase('j_walk_pitch_up_90', { ...flat, pitch: -90, tags: ['walk', 'view'] },
    press('forward', 30),
    stopped(3),
  ),
  kase('j_walk_pitch_down_90', { ...flat, pitch: 90, tags: ['walk', 'view'] },
    press('forward', 30),
    stopped(3),
  ),
  kase('j_sprint_turn_fast', { ...flat, tags: ['sprint', 'view'] },
    hold('forward', SPRINT),
    turn(20, 0, 40),
    releaseAll(),
    stopped(3),
  ),
  kase('j_sprint_jump_turn', { ...flat, tags: ['sprint', 'jump', 'view'] },
    hold('forward', SPRINT),
    ticks(8),
    press(JUMP, 1),
    turn(-9, 0, 12),
    releaseAll(),
    stopped(3),
  ),
  kase('j_strafe_circle', { ...flat, tags: ['walk', 'view'] },
    hold('forward', 'right'),
    turn(-6, 0, 60),
    releaseAll(),
    stopped(3),
  ),

  // Tiny inputs: one-tick taps, the negligible-speed cutoff while coasting.
  kase('j_tap_forward_1', { ...flat, tags: ['walk'] },
    press('forward', 1),
    stopped(3),
    ticks(3),
  ),
  kase('j_tap_forward_2', { ...flat, tags: ['walk'] },
    press('forward', 2),
    stopped(3),
    ticks(3),
  ),
  kase('j_tap_each_direction', { ...flat, tags: ['walk'] },
    repeat(4, i => [press(['forward', 'right', 'back', 'left'][i], 3), ticks(2)]),
    stopped(3),
  ),
  kase('j_opposite_keys', { ...flat, tags: ['walk'] },
    press(['forward', 'back'], 20),
    press(['left', 'right', 'forward'], 20),
    stopped(3),
  ),
  kase('j_idle', { ...flat, tags: ['idle'] },
    ticks(40),
  ),
  kase('j_jump_idle_long', { ...flat, tags: ['jump'] },
    hold(JUMP),
    ticks(200),
    releaseAll(),
    stable(5),
  )
)

export default out
