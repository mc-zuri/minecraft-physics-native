// Ported from physics-data-generator catalog/src/cases/java-flight.mjs; maintained here now.
// Elytra: deploying (and when it is refused), gliding at every pitch, pitch and yaw sweeps, rocket boosts, landing and
// relaunching, flying into a wall. Creative flight: toggling by double jump, every direction, sprint, landing, walls
// and ceilings. Spectator flight through blocks.
import './_areas/index.ts'
import { F, B, L, R, JUMP, SNEAK, SPRINT, USE, clearEffects, commandBy, giveEffect, hold, kase, look, press, release, releaseAll, server, stable, stopped, ticks, turn, until } from '../../dsl/physrec.ts'

const elytra = (extra = {}) => ({ equipment: { chest: { id: 'elytra', enchantments: {} }, mainhand: { id: 'firework_rocket', count: 64, enchantments: {} } }, ...extra })
// Off the tower's +z edge (tower top: local y 30, blocks z=-2..2 so the edge is z=3); jump pressed in the air deploys.
// A glide stops being recorded once it is on the ground or past the runway.
const tower = (extra = {}) => ({ area: 'sky', at: [0.5, 30, 2.8], yaw: 0, tier: 3, tags: ['elytra'], setup: elytra(), ...extra })
const launch = [press(F, 4), ticks(3), press(JUMP, 1)]
// After the stop, 5 more ticks: at glide speed (<2.5 blocks a tick) that stays inside the area.
const toGround = (max = 1200) => [until('onGround || z>260 || x>30 || x<-30', max), ticks(5)]
const out = []

for (const pitch of [-90, -60, -30, -15, 0, 15, 30, 45, 60, 90]) {
  out.push(kase(`f_elytra_pitch_${pitch}`, tower(),
    launch,
    look(0, pitch),
    toGround(),
  ))
}
// A glide into lava: to 1.13.2 the 0.6F box is inside out once contracted by 0.4F, and Java sorts it (B134).
for (const pitch of [20, 45]) {
  out.push(kase(`f_elytra_into_lava_${pitch}`, tower({ area: 'skyLava' }),
    launch,
    look(0, pitch),
    until('isInLava || onGround || z>46', 400),
    ticks(10),
  ))
}
out.push(
  kase('f_elytra_pitch_sweep_down_up', tower(),
    launch,
    look(0, 0),
    turn(0, 2, 30),
    turn(0, -4, 30),
    toGround(),
  ),
  kase('f_elytra_turn_right', tower(),
    launch,
    look(0, 10),
    turn(2, 0, 40),
    toGround(),
  ),
  kase('f_elytra_spiral', tower(),
    launch,
    look(0, 20),
    turn(-6, 0, 200),
    toGround(800),
  ),
  kase('f_elytra_rocket_level', tower(),
    launch,
    look(0, -10),
    press(USE, 1),
    ticks(40),
    toGround(),
  ),
  kase('f_elytra_rocket_up', tower(),
    launch,
    look(0, -50),
    press(USE, 1),
    ticks(20),
    look(0, 30),
    toGround(),
  ),
  kase('f_elytra_rocket_twice', tower(),
    launch,
    look(0, -10),
    press(USE, 1),
    ticks(25),
    press(USE, 1),
    ticks(40),
    toGround(),
  ),
  kase('f_elytra_rocket_straight_down', tower(),
    launch,
    look(0, 90),
    press(USE, 1),
    toGround(),
  ),
  kase('f_elytra_landing_shallow', tower(),
    launch,
    look(0, 8),
    until('onGround || z>260 || x>30 || x<-30', 1200),
    ticks(5),
  ),
  kase('f_elytra_land_and_relaunch', tower(),
    launch,
    look(0, 30),
    until('onGround', 1200),
    ticks(2),
    press(JUMP, 1),
    ticks(4),
    press(JUMP, 1),
    ticks(40),
    toGround(),
  ),
  kase('f_elytra_sprint_glide', tower(),
    hold(SPRINT),
    launch,
    look(0, 5),
    toGround(),
    releaseAll(),
  ),
  kase('f_elytra_wall_hit', { ...tower(), area: 'skyWall' },
    launch,
    look(0, 5),
    until('isCollidedHorizontally', 400),
    ticks(5),
    toGround(),
  ),
  kase('f_elytra_wall_hit_rocket', { ...tower(), area: 'skyWall' },
    launch,
    look(0, 25),
    press(USE, 1),
    until('isCollidedHorizontally', 400),
    ticks(5),
    toGround(),
  ),
  kase('f_elytra_keys_while_gliding', tower(),
    launch,
    look(0, 10),
    press([F, L], 30),
    press([B, R, SNEAK], 30),
    toGround(),
  ),
  kase('f_elytra_no_deploy_on_ground', { ...tower(), at: [0.5, 30, 0.5] },
    press(JUMP, 1),
    ticks(3),
    press(JUMP, 1),
    ticks(20),
  ),
  kase('f_elytra_no_deploy_held_jump', tower(),
    hold(F, JUMP),
    ticks(20),
    releaseAll(),
    toGround(),
  ),
  kase('f_elytra_no_deploy_levitation', tower(),
    server(giveEffect('levitation', 0)),
    ticks(5),
    launch,
    ticks(20),
    server(clearEffects()),
    toGround(),
  ),
  kase('f_elytra_slow_falling', {
    ...tower(),
    setup: elytra({ effects: [{ id: 'slow_falling', amplifier: 0 }] }),
  },
    launch,
    look(0, 10),
    toGround(3000),
  ),
  kase('f_elytra_without_elytra', { ...tower(), setup: { equipment: {} } },
    launch,
    ticks(20),
    toGround(),
  )
)

// Creative flight. Starting mid-air with flight on, or toggled from the ground by a double jump.
const fly = (extra = {}) => ({ area: 'flight', at: [0.5, 4, 0.5], gamemode: 'creative', tier: 3, tags: ['flight'], setup: { flying: true }, yaw: 270, ...extra })
out.push(
  kase('f_fly_toggle_on', { ...fly(), at: [0.5, 0, 0.5], setup: {} },
    press(JUMP, 1),
    ticks(3),
    press(JUMP, 1),
    ticks(30),
  ),
  kase('f_fly_toggle_on_slow_double', { ...fly(), at: [0.5, 0, 0.5], setup: {} },
    press(JUMP, 1),
    ticks(8),
    press(JUMP, 1),
    ticks(30),
  ),
  kase('f_fly_toggle_off_in_air', fly(),
    ticks(5),
    press(JUMP, 1),
    ticks(3),
    press(JUMP, 1),
    until('onGround', 100),
    ticks(5),
  ),
  kase('f_fly_hover', fly(),
    ticks(40),
  ),
  kase('f_fly_forward', fly(),
    press(F, 40),
    stable(5),
  ),
  kase('f_fly_sprint', fly(),
    press([F, SPRINT], 40),
    stable(5),
  ),
  kase('f_fly_back_strafe', fly(),
    press([B, L], 40),
    stable(5),
  ),
  kase('f_fly_up', fly(),
    press(JUMP, 20),
    stable(5),
  ),
  kase('f_fly_down_to_ground', fly(),
    press(SNEAK, 40),
    ticks(10),
  ),
  // D-165: flying 0.2 over slime, one tick of sneak down and then none, so the landing tick neither sneaks nor falls fast:
  // the slime bounces 0.09 up, under its 0.1, and steps on the player only from 1.15. Before, stepOn sits in canClimb(),
  // false for a flying player (1.12.2 Entity.java:830, Player.java:1649-1651; 1.15 Entity.java:589-591).
  kase('f_fly_land_on_slime', { ...fly(), at: [0.5, 0.2, 0.5] },
    server(commandBy({ '1.13': 'execute as @p at @s run fill ~-2 ~-1 ~-2 ~10 ~-1 ~2 slime_block', '1.8': 'execute @p ~ ~ ~ fill ~-2 ~-1 ~-2 ~10 ~-1 ~2 slime' })),
    ticks(2),
    hold(F),
    ticks(3),
    press(SNEAK, 1),
    until('onGround', 20),
    releaseAll(),
    ticks(5),
  ),
  kase('f_fly_diagonal_up', fly(),
    press([F, R, JUMP], 30),
    stable(5),
  ),
  kase('f_fly_sprint_turn', fly(),
    hold(F, SPRINT),
    turn(6, 0, 40),
    releaseAll(),
    stable(5),
  ),
  kase('f_fly_into_wall', { ...fly(), at: [24.5, 4, 0.5] },
    press([F, SPRINT], 30),
    stable(5),
  ),
  kase('f_fly_into_ceiling', { ...fly(), at: [0.5, 9, 10.5] },
    press(JUMP, 20),
    stable(5),
  ),
  kase('f_fly_pitch_ignored', { ...fly(), pitch: -90 },
    press(F, 30),
    stable(5),
  ),
  kase('f_fly_land_by_walking_off', { ...fly(), at: [0.5, 0.5, 0.5] },
    press(F, 20),
    stable(5),
  ),
  kase('f_fly_release_sprint', fly(),
    hold(F, SPRINT),
    ticks(20),
    release(SPRINT),
    ticks(20),
    releaseAll(),
    stable(5),
  ),
  kase('f_spectator_through_wall', {
    ...fly(),
    gamemode: 'spectator',
    since: '1.8',
    at: [24.5, 4, 0.5],
  },
    press([F, SPRINT], 12),
    stable(5),
  ),
  kase('f_spectator_up_down', { ...fly(), gamemode: 'spectator', since: '1.8' },
    press(JUMP, 20),
    press(SNEAK, 30),
    stable(5),
  ),
  kase('f_creative_walk_jump', { ...fly(), at: [0.5, 0, 0.5], setup: {} },
    hold(F),
    press(JUMP, 1),
    until('onGround', 40),
    releaseAll(),
    stopped(3),
  )
)

// mortal, so that the server's FLY_INTO_WALL reaches the health (B175): stopped before the landing's own damage.
const mortalGlide = (extra = {}) => ({ ...tower(), area: 'skyWall', mortal: true, ...extra })
out.push(
  kase('f_elytra_wall_hurts_head_on', mortalGlide(),
    launch,
    look(0, 5),
    until('isCollidedHorizontally', 400),
    ticks(6),
  ),
  // (-15, not 345: the server wraps the yaw it is sent, and the table's sine of the two is not the same)
  kase('f_elytra_wall_hurts_glancing', mortalGlide({ yaw: -15 }),
    launch,
    look(-15, 5),
    until('isCollidedHorizontally', 400),
    ticks(6),
  ),
  // the wall is near: too slow to hurt (6) and about the threshold (12)
  ...[6, 9, 12].map(z => kase(`f_elytra_wall_near_${z}`, mortalGlide({ area: `skyWall${z}` }),
    launch,
    look(0, 0),
    until('isCollidedHorizontally', 100),
    ticks(4),
  )),
)

// The glider's last uses (B174, B179): a chest elytra of 432 with this much damage. isUsable and nextDamageWillBreak refuse 431, and
// the server takes a point every 20 ticks of a glide and ends one it cannot go on with. Proof: fallFlying.
const worn = (damage: number) => server(commandBy({
  '1.20.5': `item replace entity @p armor.chest with elytra[damage=${damage}]`, '1.17': `item replace entity @p armor.chest with elytra{Damage:${damage}}`,
  '1.13': `replaceitem entity @p armor.chest minecraft:elytra{Damage:${damage}} 1`, '1.9': `replaceitem entity @p slot.armor.chest minecraft:elytra 1 ${damage}`,
}))
out.push(
  kase('f_elytra_last_use_no_deploy', tower(), worn(431), ticks(2), launch, ticks(20), toGround()),
  kase('f_elytra_breaks_in_glide', tower(), worn(430), ticks(2), launch, look(0, 10), toGround()),
  kase('f_elytra_breaks_second_interval', tower(), worn(429), ticks(2), launch, look(0, 10), toGround()),
  // a fresh jump where the glide is refused: in water, in lava (from 26.3), on a ladder; creative flight's second press takes it
  kase('f_elytra_jump_in_water', tower({ area: 'skyWater' }), press(F, 4), until('isInWater || onGround', 200), ticks(3), press(JUMP, 1), ticks(3), press(JUMP, 1), ticks(10)),
  kase('f_elytra_jump_in_lava', tower({ area: 'skyLava' }), press(F, 4), until('isInLava || onGround', 200), ticks(3), press(JUMP, 1), ticks(3), press(JUMP, 1), ticks(10)),
  kase('f_elytra_jump_on_ladder', tower({ area: 'skyLadder' }), launch, look(0, 30), until('isCollidedHorizontally || onGround', 200), ticks(2), press(JUMP, 1), ticks(3), press(JUMP, 1), ticks(10)),
  kase('f_elytra_creative_double_jump', tower({ gamemode: 'creative' }), press(F, 4), ticks(3), press(JUMP, 1), ticks(2), press(JUMP, 1), ticks(15)),
)

// ---- Rockets at several headings, two at once, and what ends one (B177, B178); riding and a glide stopped by a mount (B174, B176). ----
for (const [yaw, pitch] of [[45, 0], [-120, 20], [160, -30], [-30, -60]]) {
  out.push(kase(`f_elytra_rocket_yaw_${yaw}_pitch_${pitch}`, tower(), launch, look(yaw, pitch), ticks(3), press(USE, 1), ticks(18)))
}
out.push(
  kase('f_elytra_rocket_two_in_a_row', tower(), launch, look(0, 0), ticks(5), press(USE, 2), ticks(45)),
  // into the ground with the rocket alive: it follows the player and boosts no one
  kase('f_elytra_rocket_lands_while_burning', tower(), launch, look(0, 80), ticks(1), press(USE, 1), until('onGround', 80), ticks(25)),
  // the glider breaks under a burning rocket
  kase('f_elytra_rocket_when_it_breaks', tower(), worn(429), ticks(2), launch, look(0, 10), ticks(1), press(USE, 1), toGround()),
  // a rocket's hit ends it: the mobs stand across the line of flight
  kase('f_elytra_rocket_hits_a_mob', tower({ setup: elytra({ summon: [18, 22, 26, 30, 34].flatMap(z => [24, 26, 28].map(y => ({ entity: 'iron_golem', at: [0.5, y, z + 0.5], noAi: true, noGravity: true }))) }) }),
    launch, look(0, 5), ticks(1), press(USE, 1), toGround()),
  // refused to a passenger
  kase('f_elytra_no_deploy_riding_boat', tower({ setup: elytra({ mount: { entity: 'oak_boat', at: [0.5, 30, 5.5], yaw: 0 } }), serverMoves: true }), ticks(4), press(JUMP, 1), ticks(2), press(JUMP, 1), ticks(25)),
  kase('f_elytra_no_deploy_riding_pig', tower({ setup: elytra({ mount: { entity: 'pig', at: [0.5, 30, 5.5], yaw: 0, noAi: true } }), serverMoves: true }), ticks(4), press(JUMP, 1), ticks(2), press(JUMP, 1), ticks(25)),
  // a mount ends a glide: Player.canGlide, LivingEntity.updateFallFlying
  kase('f_elytra_mounted_mid_glide', tower({ since: '1.21.2', serverMoves: true }), launch, look(0, 10), ticks(4),
    server(commandBy({ '1.21.2': 'execute at @p run summon minecraft:oak_boat ~ ~ ~' })), ticks(1),
    server(commandBy({ '1.21.2': 'ride @p mount @e[type=minecraft:oak_boat,limit=1,sort=nearest]' })), ticks(15)),
)

export default out
