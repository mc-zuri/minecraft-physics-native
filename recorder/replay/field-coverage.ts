// The table of what a recorded snapshot holds and what becomes of it: every field of schema/fields.ts with its type, the
// releases that have it, how it reaches the native engine and where it is compared. Generated, so that it cannot say more
// than the registry does; a test holds docs/field-coverage.md to this.
//
//   node recorder/replay/field-coverage.ts > docs/field-coverage.md

import { NATIVE_SIM, PLAYER_FIELDS, type FieldSpec } from '../schema/fields.ts';
import { OMITTED_FIELDS } from './conformance.ts';
import { ENTITY_FAMILIES, FIELD_DECISIONS, TALLY } from './field-decisions.ts';
import { PHASE_FIELDS } from './phases.ts';

type Use = { compared: string[]; seeded: string[] };

/** How the native layer uses each recorded field. */
function uses(): Map<string, Use> {
    const out = new Map<string, Use>();
    const of = (field: string) => out.get(field) ?? out.set(field, { compared: [], seeded: [] }).get(field)!;
    for (const [key, map] of Object.entries(NATIVE_SIM)) {
        if ('from' in map && typeof map.from === 'string') {
            const use = of(map.from);
            use.compared.push(key);
            for (const [phase, fields] of Object.entries(PHASE_FIELDS)) if (fields.includes(key)) use.compared.push(`${key}@${phase}`);
        } else if ('from' in map && Array.isArray(map.from)) {
            for (const field of map.from) of(field).seeded.push(key);
        }
    }
    return out;
}

export function fieldCoverage(): string {
    const used = uses();
    const lines = [
        '# Field coverage',
        '',
        'Generated by `node recorder/replay/field-coverage.ts`; do not edit. `compared` is a native field compared at the end of the tick, `field@phase` at a phase as well; `seed only` reaches the engine and comes back in no comparison; a field with no native use has its verdict (replay/field-decisions.ts).',
        '',
        '| Field | Type | Releases | Native use |',
        '| --- | --- | --- | --- |',
    ];
    for (const [field, spec] of Object.entries(PLAYER_FIELDS as Record<string, FieldSpec>)) {
        const use = used.get(field);
        const omitted = field in OMITTED_FIELDS ? ' (not compared: see OMITTED_FIELDS)' : '';
        const decision = FIELD_DECISIONS[field];
        const text = use?.compared.length ? `compared: ${use.compared.join(', ')}${omitted}` : use?.seeded.length ? `seed only: ${use.seeded.join(', ')}` : decision ? `${decision.verdict}${decision.by ? ` (${decision.by})` : ''}: ${decision.why}` : 'recorded';
        lines.push(`| ${field} | ${spec.type} | ${spec.versions ?? 'all'} | ${text} |`);
    }
    const tally = TALLY();
    lines.push('', '## Fields with no native use, by verdict', '', ...Object.entries(tally).map(([verdict, fields]) => `- ${verdict} (${fields!.length}): ${fields!.join(', ')}`));
    lines.push('', '## Entity families', '', '| Family | Captured | Compared | By | Not held |', '| --- | --- | --- | --- | --- |');
    for (const { family, captured, compared, by, missing } of ENTITY_FAMILIES) lines.push(`| ${family} | ${captured} | ${compared} | ${by} | ${missing} |`);
    return `${lines.join('\n')}\n`;
}

if (process.argv[1]?.endsWith('field-coverage.ts')) process.stdout.write(fieldCoverage());
